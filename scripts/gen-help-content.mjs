#!/usr/bin/env node
/**
 * Generates src/lib/help/content.ts from docs/help/*.md.
 *
 * The markdown files are the authoring source of truth; content.ts is the
 * runtime bundle the in-app help drawer reads. Keeping them in sync by hand
 * drifts, so generate instead.
 *
 *   node scripts/gen-help-content.mjs           # write content.ts
 *   node scripts/gen-help-content.mjs --check   # exit 1 if out of date
 *
 * Adding a help page: add docs/help/<key>.md, then add the key to ORDER (with
 * its drawer title) and to ROUTES (with the pathname prefix it serves).
 *
 * Note the in-app renderer (src/components/help/markdown.tsx) supports only a
 * subset of markdown: # and ## headings, `-` bullets, **bold**, `code`, and
 * [links](url). H3s, ordered lists, tables, blockquotes, code fences and
 * single-asterisk italics render as literal text — this script rejects them.
 */
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "src/lib/help/content.ts";

const ORDER = [
  ["dashboard", "Dashboard"],
  ["registry", "AI System Registry"],
  ["registry-detail", "System Detail"],
  ["agents", "AI Agents"],
  ["risk-center", "Risk Center"],
  ["compliance", "Compliance"],
  ["shadow-ai", "Shadow AI Discovery"],
  ["oversight", "Oversight"],
  ["alerts", "Alerts"],
  ["executive", "Executive Dashboard"],
  ["reports", "Reports"],
  ["integrations", "Integrations"],
  ["proxy-health", "Proxy Health"],
  ["sensitive-scan", "Sensitive Scan"],
  ["settings", "Settings"],
];

// Most specific first. /registry/<id> is special-cased ahead of these.
const ROUTES = [
  ["/dashboard", "dashboard"],
  ["/registry", "registry"],
  ["/agents", "agents"],
  ["/risk-center", "risk-center"],
  ["/compliance", "compliance"],
  ["/shadow-ai", "shadow-ai"],
  ["/oversight", "oversight"],
  ["/alerts", "alerts"],
  ["/executive", "executive"],
  ["/reports", "reports"],
  ["/integrations", "integrations"],
  ["/proxy-health", "proxy-health"],
  ["/sensitive-scan", "sensitive-scan"],
  ["/settings", "settings"],
];

const q = (k) => (/^[a-z][a-z0-9]*$/.test(k) ? k : JSON.stringify(k));
const esc = (s) =>
  s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

/** Reject markdown the in-app renderer would show as literal text. */
function lintSource(key, md) {
  const problems = [];
  if (/^### /m.test(md)) problems.push("h3 heading (renderer supports # and ## only)");
  if (/^[0-9]+\. /m.test(md)) problems.push("ordered list (use - bullets)");
  if (/^> /m.test(md)) problems.push("blockquote");
  if (/^```/m.test(md)) problems.push("code fence (use `inline code`)");
  if (/^\|/m.test(md)) problems.push("table");
  if (/(^|[^*])\*[^*\s][^*]*\*([^*]|$)/m.test(md))
    problems.push("single-asterisk italics (use **bold**)");
  if (!md.startsWith("# ")) problems.push("must open with an H1");
  return problems.map((p) => `${key}.md: ${p}`);
}

const problems = [];
const sources = new Map();
for (const [key] of ORDER) {
  const md = readFileSync(`docs/help/${key}.md`, "utf8");
  sources.set(key, md);
  problems.push(...lintSource(key, md));
}
if (problems.length) {
  console.error("Unsupported markdown in help sources:\n" + problems.map((p) => `  - ${p}`).join("\n"));
  process.exit(1);
}

let out = `/**
 * In-app help content. Mirrors the canonical authoring source under
 * \`docs/help/*.md\` so contributors can edit either place — the markdown files
 * are the source of truth, this map is the runtime bundle.
 *
 * GENERATED by scripts/gen-help-content.mjs — do not hand-edit the strings
 * below. Edit the matching \`docs/help/<key>.md\` and run \`npm run help:sync\`.
 */

export type HelpKey =
${ORDER.map(([k]) => `  | ${JSON.stringify(k)}`).join("\n")};

export const HELP_TITLES: Record<HelpKey, string> = {
${ORDER.map(([k, t]) => `  ${q(k)}: ${JSON.stringify(t)},`).join("\n")}
};

export const HELP_CONTENT: Record<HelpKey, string> = {
`;
for (const [key] of ORDER) out += `  ${q(key)}: \`${esc(sources.get(key))}\`,\n`;
out += `};

/**
 * Map a Next.js pathname to a help key. Falls back to "dashboard".
 * Order matters — most specific routes come first.
 */
export function helpKeyForPath(pathname: string): HelpKey {
  if (pathname.startsWith("/registry/") && pathname !== "/registry/new") return "registry-detail";
${ROUTES.map(([p, k]) => `  if (pathname.startsWith(${JSON.stringify(p)})) return ${JSON.stringify(k)};`).join("\n")}
  return "dashboard";
}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== out) {
    console.error(
      `${OUT} is out of date with docs/help/*.md. Run \`npm run help:sync\` and commit the result.`
    );
    process.exit(1);
  }
  console.log(`${OUT} is in sync with docs/help/*.md (${ORDER.length} pages).`);
} else {
  writeFileSync(OUT, out);
  console.log(`Wrote ${OUT} from ${ORDER.length} help pages.`);
}
